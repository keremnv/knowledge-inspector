"""Disposable canonical-reference benchmark; --server can select merged main.

Each invocation uses identical generated bytes for the supplied server version.
Timing medians exclude fixture creation and the separate tracemalloc run. No
archived source is opened. SQLite memory is included only in process peak RSS.
"""
import argparse
import hashlib
import importlib.util
import json
import os
import platform
import resource
import sqlite3
import statistics
import sys
import tempfile
import time
import tracemalloc
from contextlib import closing
from pathlib import Path


def measure(function):
    start = time.perf_counter(); result = function()
    return time.perf_counter() - start, result


def retained_bytes(value, seen=None):
    # Exclude shared class objects used as storage-type tags.
    seen = set() if seen is None else seen
    if id(value) in seen or isinstance(value, type): return 0
    seen.add(id(value)); total = sys.getsizeof(value)
    if isinstance(value, dict):
        total += sum(retained_bytes(k, seen) + retained_bytes(v, seen) for k, v in value.items())
    elif isinstance(value, (list, tuple, set, frozenset)):
        total += sum(retained_bytes(v, seen) for v in value)
    return total


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server', type=Path, default=Path(__file__).with_name('server.py'))
    parser.add_argument('--shape', choices=['indexed', 'unindexed', 'view'], required=True)
    parser.add_argument('--rows', type=int, required=True)
    parser.add_argument('--reverse-affinity', action='store_true', help='TEXT targets, INTEGER participants')
    parser.add_argument('--repeated', action='store_true', help='16 target rows, repeated TEXT participants')
    parser.add_argument('--repeats', type=int, default=3)
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('bench_world', args.server)
    world = importlib.util.module_from_spec(spec); spec.loader.exec_module(world)
    with tempfile.TemporaryDirectory(prefix='ki-reference-bench-') as directory:
        path = Path(directory) / 'source.sqlite'
        target_count = 16 if args.repeated else args.rows
        with closing(sqlite3.connect(path)) as db:
            indexed = 'PRIMARY KEY' if args.shape == 'indexed' else ''
            db.execute(f'CREATE TABLE entity(id {"TEXT" if args.reverse_affinity else "INTEGER"} {indexed})')
            db.execute(f'CREATE TABLE event(id INTEGER {indexed},participant {"INTEGER" if args.reverse_affinity else "TEXT"})')
            db.executemany('INSERT INTO entity VALUES(?)', ((str(n).zfill(8) if args.reverse_affinity else n,) for n in range(target_count)))
            # TEXT zero-padded aliases accepted by main but projected incorrectly.
            db.executemany('INSERT INTO event VALUES(?,?)', ((n, n % target_count if args.reverse_affinity else str(n % target_count).zfill(8)) for n in range(args.rows)))
            if args.shape == 'view':
                db.executescript('CREATE VIEW entity_view AS SELECT id FROM entity; CREATE VIEW event_view AS SELECT id,participant FROM event;')
            db.commit()
        before = path.read_bytes(), path.stat().st_mtime_ns
        entity = 'entity_view' if args.shape == 'view' else 'entity'
        source = 'event_view' if args.shape == 'view' else 'event'
        role = {'role': 'participant', 'column_name': 'participant', 'target_kind': 'entity'}
        declared = world.validate_declaration({'version': 1,
            'entities': [{'kind': 'entity', 'source': entity, 'key_columns': ['id']}],
            'relations': [{'name': 'event', 'source': source, 'key_columns': ['id'], 'roles': [role]}]})
        samples = []
        for repeat in range(args.repeats):
            with closing(world.connect(path)) as db:
                phase = []
                original = world.Model._check_roles
                def timed_roles(self, *a, **kw):
                    elapsed, result = measure(lambda: original(self, *a, **kw)); phase.append(elapsed); return result
                world.Model._check_roles = timed_roles
                try: startup, model = measure(lambda: world.Model(db, declared))
                finally: world.Model._check_roles = original
                independent, _ = measure(lambda: model._check_roles(db, 'event', source, [role]))
                # Use canonical target ID on BOTH versions. Main's incorrect
                # empty-neighborhood result is recorded alongside its timing.
                reads = {}
                canonical_id = 'entity:00000000' if args.reverse_affinity else 'entity:0'
                for name, action in [
                    ('assertion', lambda: world.assertion(db, model, 'event:0')),
                    ('referent', lambda: world.referent(db, model, canonical_id)),
                    ('expand', lambda: world.expand(db, model, canonical_id, 'event', 200)),
                    ('rows_subject', lambda: world.rows(db, model, {'relation': ['event'], 'subject': [canonical_id]}))]:
                    elapsed, result = measure(action)
                    reads[name] = elapsed
                    if name == 'referent': neighborhood_count = result['relations'][0]['count']
                samples.append({'model': startup, 'resolution_in_model': sum(phase), 'resolution_independent': independent, **reads})
                if hasattr(world, '_reference_query'):
                    sql, alias = world._reference_query(source, 'participant', model.entities['entity'])
                    try:
                        world._require_lookup_plan(db, sql, (), model.entities['entity'], 'benchmark', alias, source)
                    except ValueError:
                        sql, alias = world._reference_query(source, 'participant', model.entities['entity'], reverse=True)
                else:
                    sql = (f'WITH target AS MATERIALIZED (SELECT id FROM "{entity}") SELECT COUNT(*)'
                           f' FROM "{source}" s LEFT JOIN target AS m ON m.id=s.participant WHERE m.id IS NULL')
                plan = [list(row) for row in db.execute('EXPLAIN QUERY PLAN ' + sql)]
                mapping = model.relations['event'].get('references', {})
                mapping_bytes = retained_bytes(mapping)
                canonical_registry_bytes = sum(retained_bytes(e.get('canonical_ids', frozenset())) for e in model.entities.values())
                distinct = sum(len(m) for m in mapping.values())
        clean_peak_rss_kib = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        del model, mapping
        with closing(world.connect(path)) as db:
            tracemalloc.start()
            model = world.Model(db, declared)
            python_retained, python_peak = tracemalloc.get_traced_memory()
            tracemalloc.stop()
        assert (path.read_bytes(), path.stat().st_mtime_ns) == before
        assert not list(path.parent.glob(path.name + '-*'))
        output = {
            'shape': args.shape, 'rows': args.rows, 'targets': target_count, 'repeated': args.repeated, 'reverse_affinity': args.reverse_affinity,
            'server_sha256': hashlib.sha256(args.server.read_bytes()).hexdigest(),
            'fixture_sha256': hashlib.sha256(before[0]).hexdigest(),
            'environment': {'python': sys.version, 'sqlite': sqlite3.sqlite_version, 'platform': platform.platform(), 'cpu_count': os.cpu_count()},
            'samples': samples, 'medians_seconds': {key: statistics.median(s[key] for s in samples) for key in samples[0]},
            'canonical_neighborhood_count': neighborhood_count, 'distinct_mapped_participants': distinct,
            'mapping_retained_bytes': mapping_bytes, 'canonical_id_registry_bytes': canonical_registry_bytes,
            'python_model_retained_bytes': python_retained, 'python_model_peak_bytes': python_peak,
            'process_peak_rss_kib_before_tracemalloc': clean_peak_rss_kib,
            'plan': plan, 'source_unchanged': True,
        }
        print(json.dumps(output, indent=2))


if __name__ == '__main__':
    main()
